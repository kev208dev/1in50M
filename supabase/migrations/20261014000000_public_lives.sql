create table if not exists public.public_lives (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  alias text not null check (char_length(alias) between 1 and 40),
  age smallint not null check (age between 0 and 120),
  birth_region text not null check (char_length(birth_region) between 1 and 40),
  final_region text not null check (char_length(final_region) between 1 and 40),
  career text not null check (char_length(career) between 1 and 60),
  net_worth_band text not null check (char_length(net_worth_band) between 1 and 30),
  reflection text not null check (char_length(reflection) between 1 and 180),
  completed_at timestamptz not null,
  hidden boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.life_reactions (
  id bigint generated by default as identity primary key,
  life_id uuid not null references public.public_lives(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('remember', 'resonate')),
  created_at timestamptz not null default now(),
  unique (life_id, owner_id, kind)
);

create index if not exists public_lives_visible_recent_idx
  on public.public_lives (completed_at desc)
  where hidden = false;

create index if not exists life_reactions_life_id_idx
  on public.life_reactions (life_id);

alter table public.public_lives enable row level security;
alter table public.life_reactions enable row level security;

revoke all on public.public_lives from anon, authenticated;
revoke all on public.life_reactions from anon, authenticated;
grant select, insert, update on public.public_lives to authenticated;
grant select, insert, delete on public.life_reactions to authenticated;
grant usage, select on sequence public.life_reactions_id_seq to authenticated;

create policy "visible lives are readable"
  on public.public_lives for select
  to authenticated
  using (hidden = false or auth.uid() = owner_id);

create policy "owners publish their lives"
  on public.public_lives for insert
  to authenticated
  with check (auth.uid() = owner_id);

create policy "owners hide their lives"
  on public.public_lives for update
  to authenticated
  using (auth.uid() = owner_id)
  with check (auth.uid() = owner_id);

create policy "reactions are readable"
  on public.life_reactions for select
  to authenticated
  using (true);

create policy "owners add reactions"
  on public.life_reactions for insert
  to authenticated
  with check (auth.uid() = owner_id);

create policy "owners remove reactions"
  on public.life_reactions for delete
  to authenticated
  using (auth.uid() = owner_id);

create or replace function public.set_public_life_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger set_public_life_updated_at
before update on public.public_lives
for each row execute function public.set_public_life_updated_at();

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'public_lives'
  ) then
    alter publication supabase_realtime add table public.public_lives;
  end if;
end;
$$;
